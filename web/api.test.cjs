const assert=require('node:assert/strict');
const {translate}=require('./api.cjs');
const coordinator=require('./coordinator.cjs');
assert.deepEqual(translate('grok_read',{agentId:'bot',limit:20}),['getAgentTranscriptTail',{id:'bot',limit:20}]);
assert.throws(()=>translate('grok_send',{agentId:'bot',prompt:'hi'}),/clientNonce/);
assert.throws(()=>translate('grok_read',{agentId:'bot',limit:501}),/limit/);
assert.throws(()=>translate('grok_send',{agentId:'bot',prompt:'hi',clientNonce:'unique',approval:true}),/Unknown/);
const browser=[],results=[],sent=[];let receive;
const c=coordinator({browser:m=>browser.push(m),result:m=>results.push(m)});
c.attach({addEventListener:(_,fn)=>receive=fn,start(){},postMessage:m=>sent.push(m),close(){}});
assert.equal(sent[0].phase,'hello');
c.request('queued','getServerAgentRoster',{});assert.equal(sent.length,1);
c.browserAttach();c.browserSend({kind:'lifecycle',phase:'hello',protocolVersion:3});
receive({data:{kind:'lifecycle',phase:'ready',protocolVersion:3}});
assert.equal(browser[0].phase,'ready');assert.equal(sent.at(-1).requestId,'api:queued');c.cancel('queued');
c.request('a','getServerAgentRoster',{});
c.browserSend({kind:'request',requestId:'r-1',method:'getServerAgentRoster',args:{}});
receive({data:{kind:'reply',requestId:'api:a',outcome:{status:'ok',value:{}}}});
assert.equal(results.length,1);assert.equal(browser.length,1);
receive({data:{kind:'reply',requestId:'web:1:r-1',outcome:{status:'ok',value:{}}}});
assert.equal(browser.length,2);assert.equal(browser.at(-1).requestId,'r-1');
c.browserDetach();c.request('b','getServerAgentRoster',{});
receive({data:{kind:'reply',requestId:'api:b',outcome:{status:'ok',value:{}}}});
assert.equal(results.length,2);
c.browserAttach();c.browserSend({kind:'lifecycle',phase:'hello',protocolVersion:3});
const before=browser.length;receive({data:{kind:'reply',requestId:'web:1:r-1',outcome:{status:'ok'}}});assert.equal(browser.length,before);
assert.equal(browser.at(-1).phase,'ready');assert.equal(sent.filter(m=>m.phase==='hello').length,1);
assert.throws(()=>c.browserSend({kind:'request',requestId:'api:fake'}),/Reserved/);
c.request('c','sendPrompt',{});c.cancel('c');assert.equal(sent.at(-1).kind,'cancel');
c.request('d','sendPrompt',{});receive({data:{kind:'lifecycle',phase:'shutdown'}});
assert.match(results.at(-1).error,/unknown/);
console.log('API validation and coordinator isolation passed');
